"""Generate src/sine_table.c: sin(0..90 degrees) in Q15, stored in PROGMEM.

Q15 means the value is scaled by 32767, so sin(90) = 32767 and a product
r * sin_q15 / 32768 gives r * sin(angle) in integer math.

Usage: python tools/gen_sine.py
"""

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "sine_table.c"


def main():
    values = [round(32767 * math.sin(math.radians(d))) for d in range(91)]
    rows = []
    for i in range(0, 91, 8):
        chunk = ", ".join(f"{v:5d}" for v in values[i : i + 8])
        rows.append(f"    {chunk},  /* {i}.. */")
    out = [
        "/*",
        " * sine_table.c - sin(0..90 degrees) in Q15 (x 32767), 1 degree steps.",
        " *",
        " * GENERATED by tools/gen_sine.py. Do not edit.",
        " * The other quadrants come from symmetry in trig.c.",
        " */",
        "",
        '#include "trig.h"',
        "",
        "const int16_t sine_q15_table[91] PROGMEM = {",
        *rows,
        "};",
        "",
    ]
    OUT.write_text("\n".join(out), newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
