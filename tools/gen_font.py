"""Generate src/font5x7.c from tools/font5x7.txt.

Each glyph is stored as 5 column bytes. Bit 0 of a column byte is the top
row and bit 6 is the bottom row, so drawing a character is a loop over 5
columns and 7 bits.

Usage: python tools/gen_font.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "font5x7.txt"
OUT = ROOT / "src" / "font5x7.c"

FIRST, LAST = 0x20, 0x7E
WIDTH, HEIGHT = 5, 7


def parse(text):
    glyphs = {}
    lines = [ln.rstrip() for ln in text.splitlines()]
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("char "):
            parts = line.split()
            code = int(parts[1], 16)
            name = parts[2] if len(parts) > 2 else ""
            rows = lines[i + 1 : i + 1 + HEIGHT]
            for r in rows:
                if len(r) != WIDTH or set(r) - {"#", "."}:
                    raise SystemExit(f"bad row {r!r} in glyph 0x{code:02X}")
            glyphs[code] = (name, rows)
            i += 1 + HEIGHT
        else:
            i += 1
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        raise SystemExit("missing glyphs: " + ", ".join(f"0x{c:02X}" for c in missing))
    return glyphs


def columns(rows):
    cols = []
    for x in range(WIDTH):
        byte = 0
        for y in range(HEIGHT):
            if rows[y][x] == "#":
                byte |= 1 << y
        cols.append(byte)
    return cols


def main():
    glyphs = parse(SRC.read_text())
    out = [
        "/*",
        " * font5x7.c - 5x7 pixel font, printable ASCII 0x20-0x7E.",
        " *",
        " * GENERATED by tools/gen_font.py from tools/font5x7.txt. Do not edit.",
        " * 5 bytes per glyph, one per column, left to right.",
        " * Bit 0 = top row, bit 6 = bottom row. Stored in flash (PROGMEM).",
        " */",
        "",
        '#include "font5x7.h"',
        "",
        f"const uint8_t font5x7[FONT_COUNT][FONT_W] PROGMEM = {{",
    ]
    for code in range(FIRST, LAST + 1):
        name, rows = glyphs[code]
        data = ", ".join(f"0x{b:02X}" for b in columns(rows))
        out.append(f"    {{ {data} }}, /* 0x{code:02X} {name} */")
    out.append("};")
    out.append("")
    OUT.write_text("\n".join(out), newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({LAST - FIRST + 1} glyphs)")


if __name__ == "__main__":
    main()
